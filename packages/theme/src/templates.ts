export function getTemplate(id?: string): DocumentTemplateMeta {
  if (!id) return TEMPLATES.modern || TEMPLATES['in-gst'] || TEMPLATES.cleartax_gst;
  if (TEMPLATES[id]) return TEMPLATES[id];
  const target = TEMPLATE_ALIAS[id];
  if (target && TEMPLATES[target]) return TEMPLATES[target];
  return TEMPLATES.modern || TEMPLATES['in-gst'] || TEMPLATES.cleartax_gst;
}

export function getTemplatesByCategory(): {
  category: TemplateCategory;
  label: string;
  templates: DocumentTemplateMeta[];
}[] {
  return TEMPLATE_CATEGORIES.map((cat) => ({
    category: cat.id,
    label: cat.label,
    templates: Object.values(TEMPLATES).filter((t) => t.category === cat.id),
  }));
}
